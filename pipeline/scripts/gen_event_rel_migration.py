"""Generate a reviewable migration that removes the two systematic event-edge schema
violations graph-wide (the live counterpart of the extract_facts.py guards added in the
Pedro Sánchez ego audit, run 20260619):

  * PARTICIPATED_IN → Person   (nothing "participates in" a person)
  * INVOLVES Person → Person   (a person does not "involve" another person)

Both are extraction artifacts (none are source_kind='contexto'); the genuine link, when
it exists, is a differently-typed edge the extractor emits separately. Mirrors the
`manual_fix_accused_of` precedent. Writes a per-edge DELETE + a faithful per-edge rollback
CREATE (located by endpoints + source_chunk_id), to be applied with the GATED
`make qa-migrate FILE=… CONFIRM=1`. Read-only against Neo4j — it only emits files.

    cd pipeline && uv run python -m scripts.gen_event_rel_migration
"""
from __future__ import annotations

from pathlib import Path

from src import config, neo4j_loader

OUT_DIR = config.WORK_DIR / "audit" / "patches"
STAMP = "20260619"  # date-stamped; no Date.now() so the run stays reproducible
MIG = OUT_DIR / f"manual_fix_event_rels_{STAMP}.cypher"
RBK = OUT_DIR / f"manual_fix_event_rels_{STAMP}.rollback.cypher"

# (label, cypher selecting the offending edges). Both endpoints carry entity_id.
QUERIES = [
    ("PARTICIPATED_IN→Person",
     "MATCH (a)-[r:PARTICIPATED_IN]->(b:Person) RETURN a,b,r"),
    ("INVOLVES Person→Person",
     "MATCH (a:Person)-[r:INVOLVES]->(b:Person) RETURN a,b,r"),
]
PROP_KEYS = ["source_kind", "source_doc", "source_page", "source_chunk_id",
             "source_quote", "amount", "currency", "date"]


def _lit(v) -> str:
    """Cypher literal for a captured property value."""
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "\\'") + "'"


def main() -> None:
    driver = neo4j_loader.get_driver()
    mig_lines, rbk_lines, n = [], [], 0
    try:
        with driver.session() as s:
            for label, cy in QUERIES:
                for rec in s.run(cy):
                    a, b, r = rec["a"], rec["b"], rec["r"]
                    sid, tid, rtype = a["entity_id"], b["entity_id"], r.type
                    chunk = r.get("source_chunk_id")
                    if not chunk:
                        continue  # never seen (all have one), but stay safe
                    props = {k: r.get(k) for k in PROP_KEYS if r.get(k) is not None}
                    propstr = ",".join(f"{k}:{_lit(v)}" for k, v in props.items())
                    head = f"// [{label}] ({a.get('name')}) -[{rtype}]-> ({b.get('name')})"
                    mig_lines.append(
                        f"{head}\nMATCH (a {{entity_id:{_lit(sid)}}})-[r:{rtype}]->"
                        f"(b {{entity_id:{_lit(tid)}}}) WHERE r.source_chunk_id={_lit(chunk)} DELETE r;\n")
                    rbk_lines.append(
                        f"{head}\nMATCH (a {{entity_id:{_lit(sid)}}}),(b {{entity_id:{_lit(tid)}}}) "
                        f"CREATE (a)-[:{rtype} {{{propstr}}}]->(b);\n")
                    n += 1
    finally:
        driver.close()

    banner = (f"// GENERATED by gen_event_rel_migration.py — {n} edge(s). REVISABLE Y REVERSIBLE.\n"
              f"// Systematic schema fix: PARTICIPATED_IN→Person + INVOLVES Person→Person (extraction\n"
              f"// artifacts; root guarded in extract_facts.py). Apply GATED: make qa-migrate FILE=… CONFIRM=1.\n\n")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    MIG.write_text(banner + "\n".join(mig_lines))
    RBK.write_text(banner.replace(f"{n} edge(s)", f"{n} ROLLBACK") + "\n".join(rbk_lines))
    print(f"✔ {n} sentencias → {MIG}")
    print(f"  rollback        → {RBK}")


if __name__ == "__main__":
    main()
