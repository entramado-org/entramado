"""Genera migración + rollback para eliminar el nodo basura Crime:delito.

Crime:delito es un artefacto de extracción: un nodo :Crime cuyo nombre es la palabra
genérica "delito". Sus 11 aristas semánticas usan "delito" como boilerplate (no un delito
concreto) y CADA figura conserva sus delitos reales en nodos propios (cohecho, malversación,
tráfico de influencias, blanqueo, falsedad-documental, prevaricación, revelación-de-secretos,
delito-contra-la-hacienda-publica). Borrar el nodo NO pierde ninguna atribución real.

DETACH DELETE solo elimina las relaciones DEL nodo (incl. 36 MENTIONED_IN→:Chunk); los
:Chunk/:Document y su texto quedan intactos. El rollback recrea nodo + TODAS sus relaciones
con sus propiedades → 100% reversible.
"""
import os
import sys, json
from neo4j import GraphDatabase

STAMP = sys.argv[1] if len(sys.argv) > 1 else "manual"
EID = "Crime:delito"
OUT = "data/audit/patches"

def cy_val(v):
    if v is None: return "null"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return repr(v)
    if isinstance(v, list): return "[" + ", ".join(cy_val(x) for x in v) + "]"
    s = str(v).replace("\\", "\\\\").replace("'", "\\'")
    return "'" + s + "'"

def cy_map(props):
    return "{" + ", ".join(f"{k}: {cy_val(v)}" for k, v in props.items()) + "}"

d = GraphDatabase.driver("bolt://localhost:7687", auth=("neo4j", os.getenv("NEO4J_PASSWORD", "changeme")))
with d.session() as s:
    node = s.run("MATCH (c {entity_id:$e}) RETURN labels(c) AS labels, properties(c) AS props", e=EID).single()
    labels = [l for l in node["labels"]]
    nprops = dict(node["props"])
    # drop embedding if present (huge / not on Crime, but be safe)
    nprops.pop("embedding", None)

    rels = []
    for x in s.run("""
        MATCH (c {entity_id:$e})-[r]-(o)
        RETURN type(r) AS rt,
               startNode(r).entity_id = $e AS outgoing,
               coalesce(o.entity_id, o.chunk_id) AS okey,
               (o.entity_id IS NOT NULL) AS is_entity,
               labels(o) AS olbl,
               properties(r) AS rp
    """, e=EID):
        rels.append(dict(x))

n_sem = sum(1 for r in rels if r["is_entity"])
n_men = sum(1 for r in rels if not r["is_entity"])

# ---------- migration ----------
mig = []
mig.append(f"// GENERATED by gen_crime_delito_cleanup.py — elimina el nodo basura Crime:delito.")
mig.append(f"// Artefacto de extracción: :Crime cuyo nombre es la palabra genérica 'delito'.")
mig.append(f"// {n_sem} aristas semánticas (boilerplate) + {n_men} MENTIONED_IN→:Chunk. DETACH DELETE")
mig.append(f"// solo borra SUS relaciones; los :Chunk/:Document quedan intactos. REVISABLE Y REVERSIBLE.")
mig.append(f"// Apply GATED: make qa-migrate FILE=… CONFIRM=1.  Tras aplicar: make centralidad.")
mig.append("")
mig.append(f"MATCH (c {{entity_id:'{EID}'}}) DETACH DELETE c;")
mig.append("")
open(f"{OUT}/manual_fix_crime_delito_{STAMP}.cypher", "w").write("\n".join(mig))

# ---------- rollback ----------
rb = []
rb.append(f"// ROLLBACK de manual_fix_crime_delito_{STAMP}.cypher — recrea Crime:delito + todas sus relaciones.")
rb.append(f"// Recrea el nodo con sus props y las {n_sem} aristas semánticas + {n_men} MENTIONED_IN.")
rb.append(f"// (centralidad/community se recalculan con `make centralidad`; aquí se restauran tal cual).")
rb.append("")
lbl = ":" + ":".join(labels)
rb.append(f"CREATE (c{lbl} {cy_map(nprops)});")
rb.append("")
for r in rels:
    if r["is_entity"]:
        match_o = f"(o {{entity_id:{cy_val(r['okey'])}}})"
    else:
        match_o = f"(o:Chunk {{chunk_id:{cy_val(r['okey'])}}})"
    rp = cy_map(r["rp"]) if r["rp"] else ""
    relpat = f"[:{r['rt']}{(' ' + rp) if rp else ''}]"
    if r["outgoing"]:
        pat = f"(c)-{relpat}->(o)"
    else:
        pat = f"(c)<-{relpat}-(o)"
    rb.append(f"MATCH (c {{entity_id:'{EID}'}}), {match_o} CREATE {pat};")
rb.append("")
open(f"{OUT}/manual_fix_crime_delito_{STAMP}.rollback.cypher", "w").write("\n".join(rb))

print(f"node labels={labels}  props={list(nprops)}")
print(f"semantic edges={n_sem}  mentioned_in={n_men}  total={len(rels)}")
print(f"wrote {OUT}/manual_fix_crime_delito_{STAMP}.cypher (+ .rollback.cypher)")
d.close()
