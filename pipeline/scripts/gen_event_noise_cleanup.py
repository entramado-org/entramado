"""Genera migración + rollback para eliminar :Event de grado≤1 que son ARTEFACTOS de extracción.

Complementa gen_generic_events_cleanup.py (sesión 42, que borró 56 :Event de sustantivo genérico
por blocklist de nombres). Aquí el criterio es por PATRÓN de alta precisión sobre nodos :Event con
grado≤1 (apenas conectados), cazando clases inequívocamente no-evento:

  - hex/code       : hashes EXIF/dispositivo (0xB07933E…)
  - fecha          : fechas sueltas ("19 de mayo", "5 de marzo de 2024")
  - IBAN/cuenta    : números de cuenta (ES34…, 2807912220200004867)
  - hora           : marcas de tiempo ("21:06 horas", "7:32:34 UTC", "13:26 h.")
  - media/fichero  : nombres de archivo (.wav/.m4a/.jpg/.zip/.sqlitedb, "Archivo ZIP", "CD152")
  - num/importe/%  : números desnudos / porcentajes ("206.000", "91,7%")
  - artículo/ley   : referencias legales ("art. 588 bis a LECrim", "Artículo 25 LOTJ")
  - folio          : referencias a folios ("Folio n° 247")

PRESERVA deliberadamente nombres propios de eventos/obras (A-44 Tramo Albolote, Autovía Orbital de
Barcelona, Acceso al Puerto de Barcelona, Cese de Ábalos…) — son el núcleo del caso de obra pública.
El filtro es por patrón estricto anclado (^…$ donde aplica), nunca por substring genérico.

DETACH DELETE solo elimina las relaciones DE cada nodo (los :Chunk/:Document quedan intactos); el
rollback recrea cada nodo + TODAS sus relaciones → 100% reversible. Reproducible: re-derivación en
vivo. Uso: `cd pipeline && uv run python scripts/gen_event_noise_cleanup.py <stamp>`.
"""
import os
import re
import sys
from neo4j import GraphDatabase

STAMP = sys.argv[1] if len(sys.argv) > 1 else "manual"
OUT = "data/audit/patches"

MESES = r"enero|febrero|marzo|abril|mayo|junio|julio|agosto|septiembre|octubre|noviembre|diciembre"
PATTERNS = [
    ("media/fichero", re.compile(r"\.(wav|m4a|mp3|mp4|jpg|jpeg|png|pdf|zip|xlsx?|docx?|sqlitedb|csv|txt|m4v|mov|amr|ogg|aac)$|^archivo zip$|^cd'?s?$|^cd ?\d+$", re.I)),
    ("hex/code", re.compile(r"^0x[0-9a-z]+$", re.I)),
    ("IBAN/cuenta", re.compile(r"^[a-z]{2}\d{6,}$|^\d{9,}$|^\d{3,}( \d{2,}){2,}$", re.I)),
    ("hora", re.compile(r"^\d{1,2}[:.]\d{2}([:.]\d{2})?\s*(h\.?|horas?|utc)?$", re.I)),
    ("fecha", re.compile(r"^\d{1,2}\s+de\s+(" + MESES + r")(\s+de\s+\d{4})?$", re.I)),
    ("folio", re.compile(r"^folios?\s*n[º°o\.]", re.I)),
    ("artículo/ley", re.compile(r"art[íi]culo|^art\.|lecrim|lopj|lotj|ljca|real decreto|convenio españa", re.I)),
    ("num/importe/%", re.compile(r"^[€$]?\s*[0-9][0-9.\,]*\s*(euros?|eur|€|millones?|%|\$)?\s*$", re.I)),
]


def classify(nm):
    nm = (nm or "").strip()
    for label, rx in PATTERNS:
        if rx.search(nm):
            return label
    return None


def cy_val(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list):
        return "[" + ", ".join(cy_val(x) for x in v) + "]"
    s = str(v).replace("\\", "\\\\").replace("'", "\\'")
    return "'" + s + "'"


def cy_map(props):
    return "{" + ", ".join(f"{k}: {cy_val(v)}" for k, v in props.items()) + "}"


d = GraphDatabase.driver("bolt://localhost:7687", auth=("neo4j", os.getenv("NEO4J_PASSWORD", "changeme")))

nodes = []
all_rels = {}
labels_by_eid = {}
tot_sem = tot_men = 0
with d.session() as s:
    cand = [(r["eid"], r["nm"]) for r in s.run(
        "MATCH (n:Event) WITH n, COUNT{(n)--()} AS deg WHERE deg<=1 "
        "RETURN n.entity_id AS eid, n.name AS nm")]
    eids = [eid for eid, nm in cand if eid and classify(nm)]
    for eid in eids:
        node = s.run(
            "MATCH (c {entity_id:$e}) RETURN labels(c) AS labels, properties(c) AS props", e=eid
        ).single()
        if node is None:
            print(f"WARN: {eid} no existe (saltado)")
            continue
        nprops = dict(node["props"])
        nprops.pop("embedding", None)
        nodes.append((eid, list(node["labels"]), nprops))
        rels = []
        for x in s.run(
            """
            MATCH (c {entity_id:$e})-[r]-(o)
            RETURN type(r) AS rt,
                   startNode(r).entity_id = $e AS outgoing,
                   coalesce(o.entity_id, o.chunk_id) AS okey,
                   (o.entity_id IS NOT NULL) AS is_entity,
                   properties(r) AS rp
            """,
            e=eid,
        ):
            rels.append(dict(x))
        all_rels[eid] = rels
        tot_sem += sum(1 for r in rels if r["is_entity"])
        tot_men += sum(1 for r in rels if not r["is_entity"])

n = len(nodes)

mig = []
mig.append("// GENERATED by gen_event_noise_cleanup.py — elimina :Event grado≤1 que son artefactos de extracción.")
mig.append(f"// {n} nodos (hex/fecha/hora/IBAN/fichero/num/artículo-ley/folio). Preserva obras y eventos con nombre.")
mig.append(f"// {tot_sem} aristas semánticas + {tot_men} MENTIONED_IN→:Chunk. :Chunk/:Document intactos. REVERSIBLE.")
mig.append("// Apply GATED: make qa-migrate FILE=… CONFIRM=1.  Tras aplicar: make centralidad && make healthcheck.")
mig.append("")
for eid, _, _ in nodes:
    mig.append(f"MATCH (c {{entity_id:'{eid}'}}) DETACH DELETE c;")
mig.append("")
open(f"{OUT}/manual_fix_event_noise_{STAMP}.cypher", "w").write("\n".join(mig))

rb = []
rb.append(f"// ROLLBACK de manual_fix_event_noise_{STAMP}.cypher — recrea los {n} nodos + sus relaciones.")
rb.append("")
for eid, labels, nprops in nodes:
    lbl = ":" + ":".join(labels)
    rb.append(f"CREATE (c{lbl} {cy_map(nprops)});")
rb.append("")
for eid, _, _ in nodes:
    for r in all_rels[eid]:
        if r["is_entity"]:
            match_o = f"(o {{entity_id:{cy_val(r['okey'])}}})"
        else:
            match_o = f"(o:Chunk {{chunk_id:{cy_val(r['okey'])}}})"
        rp = cy_map(r["rp"]) if r["rp"] else ""
        relpat = f"[:{r['rt']}{(' ' + rp) if rp else ''}]"
        pat = f"(c)-{relpat}->(o)" if r["outgoing"] else f"(c)<-{relpat}-(o)"
        rb.append(f"MATCH (c {{entity_id:'{eid}'}}), {match_o} CREATE {pat};")
rb.append("")
open(f"{OUT}/manual_fix_event_noise_{STAMP}.rollback.cypher", "w").write("\n".join(rb))

print(f"nodos={n}  semantic_edges={tot_sem}  mentioned_in={tot_men}")
print(f"wrote {OUT}/manual_fix_event_noise_{STAMP}.cypher (+ .rollback.cypher)")
d.close()
