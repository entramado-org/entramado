"""Genera migración + rollback para eliminar los nodos :MoneyAmount (money-as-node).

Son un error sistemático de modelado, inducido por la regla del prompt de extracción que
ordenaba "importes de dinero como entidad MoneyAmount". Un importe NO es una contraparte: una
arista de flujo de dinero debe conectar dos actores con el importe como PROPIEDAD de la arista
(campos `amount`/`currency`, que YA existen en cada arista). Un nodo :MoneyAmount:

  - como OBJETO de PAID/RECEIVED/INVOLVES/CONTROLS/… rompe el flujo (no hay pagador/receptor):
    p.ej. `(Koldo) -[RECEIVED 450000]-> (450000)` — el importe está duplicado en la propiedad y
    el contraparte se ha perdido; a veces nodo y propiedad se CONTRADICEN (Ezequias PAID prop=88000
    → "1800 euros"; Innova RECEIVED prop=14800 → "1800 euros").
  - como SUJETO (21 aristas salientes) es absurdo: un importe no "recibe"/"participa".

Verificado (grep repo-wide): NINGÚN código (api/mcp/web/pipeline) consulta la etiqueta
:MoneyAmount; flujos_dinero y /flujos usan aristas actor↔actor con propiedad `amount`. Por tanto
borrar estos nodos NO toca el modelo real de flujo (PAID Person=137/Company=78… intactos) ni rompe
downstream. Los overlays YAML (merges.yaml, relations_swarm_*.yaml) que referencian targets
MoneyAmount son reglas deny/fix/merge → quedan como no-ops inofensivos al no existir los nodos.

DETACH DELETE solo elimina las relaciones DE cada nodo (incl. los MENTIONED_IN→:Chunk); los
:Chunk/:Document y su texto quedan intactos. El rollback recrea cada nodo + TODAS sus relaciones
con sus propiedades → 100% reversible.

Reproducible: `MATCH (n:MoneyAmount)` en vivo → re-correr regenera idéntico mientras el grafo no
cambie. Uso: `cd pipeline && uv run python scripts/gen_money_node_cleanup.py <stamp>`.
"""
import os
import sys
from neo4j import GraphDatabase

STAMP = sys.argv[1] if len(sys.argv) > 1 else "manual"
OUT = "data/audit/patches"


def cy_val(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list):
        return "[" + ", ".join(cy_val(x) for x in v) + "]"
    s = str(v).replace("\\", "\\\\").replace("'", "\\'")
    return "'" + s + "'"


def cy_map(props):
    return "{" + ", ".join(f"{k}: {cy_val(v)}" for k, v in props.items()) + "}"


d = GraphDatabase.driver("bolt://localhost:7687", auth=("neo4j", os.getenv("NEO4J_PASSWORD", "changeme")))

nodes = []     # (eid, labels, props)
all_rels = {}  # eid -> [rel dicts]
tot_sem = tot_men = 0
with d.session() as s:
    eids = [r["e"] for r in s.run(
        "MATCH (n:MoneyAmount) WHERE n.entity_id IS NOT NULL RETURN n.entity_id AS e ORDER BY e")]
    for eid in eids:
        node = s.run(
            "MATCH (c {entity_id:$e}) RETURN labels(c) AS labels, properties(c) AS props", e=eid
        ).single()
        if node is None:
            print(f"WARN: {eid} no existe (saltado)")
            continue
        nprops = dict(node["props"])
        nprops.pop("embedding", None)
        nodes.append((eid, list(node["labels"]), nprops))
        rels = []
        for x in s.run(
            """
            MATCH (c {entity_id:$e})-[r]-(o)
            RETURN type(r) AS rt,
                   startNode(r).entity_id = $e AS outgoing,
                   coalesce(o.entity_id, o.chunk_id) AS okey,
                   (o.entity_id IS NOT NULL) AS is_entity,
                   properties(r) AS rp
            """,
            e=eid,
        ):
            rels.append(dict(x))
        all_rels[eid] = rels
        tot_sem += sum(1 for r in rels if r["is_entity"])
        tot_men += sum(1 for r in rels if not r["is_entity"])

n = len(nodes)

# ---------- migration ----------
mig = []
mig.append("// GENERATED by gen_money_node_cleanup.py — elimina los nodos :MoneyAmount (money-as-node).")
mig.append(f"// {n} nodos :MoneyAmount (importes como entidad = error de modelado inducido por el prompt).")
mig.append(f"// {tot_sem} aristas semánticas (objeto/sujeto = importe; importe ya en la propiedad de la arista)")
mig.append(f"// + {tot_men} MENTIONED_IN→:Chunk. DETACH DELETE solo borra SUS relaciones; :Chunk/:Document intactos.")
mig.append("// Modelo real de flujo (actor↔actor con propiedad amount) NO se toca. REVISABLE Y REVERSIBLE.")
mig.append("// Apply GATED: make qa-migrate FILE=… CONFIRM=1.  Tras aplicar: make centralidad && make healthcheck.")
mig.append("")
for eid, _, _ in nodes:
    mig.append(f"MATCH (c {{entity_id:'{eid}'}}) DETACH DELETE c;")
mig.append("")
open(f"{OUT}/manual_fix_money_nodes_{STAMP}.cypher", "w").write("\n".join(mig))

# ---------- rollback ----------
rb = []
rb.append(f"// ROLLBACK de manual_fix_money_nodes_{STAMP}.cypher — recrea los {n} nodos + todas sus relaciones.")
rb.append(f"// Recrea cada nodo con sus props + {tot_sem} aristas semánticas + {tot_men} MENTIONED_IN.")
rb.append("// (centralidad/community se recalculan con `make centralidad`; aquí se restauran tal cual).")
rb.append("")
for eid, labels, nprops in nodes:
    lbl = ":" + ":".join(labels)
    rb.append(f"CREATE (c{lbl} {cy_map(nprops)});")
rb.append("")
for eid, _, _ in nodes:
    for r in all_rels[eid]:
        if r["is_entity"]:
            match_o = f"(o {{entity_id:{cy_val(r['okey'])}}})"
        else:
            match_o = f"(o:Chunk {{chunk_id:{cy_val(r['okey'])}}})"
        rp = cy_map(r["rp"]) if r["rp"] else ""
        relpat = f"[:{r['rt']}{(' ' + rp) if rp else ''}]"
        pat = f"(c)-{relpat}->(o)" if r["outgoing"] else f"(c)<-{relpat}-(o)"
        rb.append(f"MATCH (c {{entity_id:'{eid}'}}), {match_o} CREATE {pat};")
rb.append("")
open(f"{OUT}/manual_fix_money_nodes_{STAMP}.rollback.cypher", "w").write("\n".join(rb))

# ---------- breakdown of semantic edges (for the gate) ----------
from collections import Counter
sem_by_type = Counter()
for eid, _, _ in nodes:
    for r in all_rels[eid]:
        if r["is_entity"]:
            sem_by_type[(r["rt"], "out" if r["outgoing"] else "in")] += 1
print(f"nodos={n}  semantic_edges={tot_sem}  mentioned_in={tot_men}")
print("semantic edges by type/dir:")
for (rt, dr), c in sem_by_type.most_common():
    print(f"  {c:4d}  {rt} ({dr})")
print(f"wrote {OUT}/manual_fix_money_nodes_{STAMP}.cypher (+ .rollback.cypher)")
d.close()
