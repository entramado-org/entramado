"""Generate the gated, reversible migration that RETIRES all entity-entity edges
sourced from parliamentary transcripts (Diario de Sesiones) — owner decision
"Option D" (findings/aristas-transcripciones-parlamentarias, 2026-07-02).

Document/Chunk/MENTIONED_IN are left untouched: the transcripts stay consultable
via /documentos + buscar_documentos + leer_documento. Only the entity-entity edges
(overwhelmingly boilerplate/co-mention/rhetoric) are removed.

Reproducible: queries the graph for the exact edges (keyed by source_chunk_id, the
load-time MERGE key) and emits
  data/audit/patches/manual_fix_transcript_edges_<stamp>.cypher            (DELETE)
  data/audit/patches/manual_fix_transcript_edges_<stamp>.rollback.cypher   (re-MERGE)

Usage (against the ephemeral read-only copy, to generate; NOT against prod):
    cd pipeline && NEO4J_URI=bolt://<sm-dev-ip>:7688 NEO4J_PASSWORD=... \
        uv run python -m scripts.gen_transcript_edge_cleanup 20260702
Apply GATED to live:  make qa-migrate FILE=<the .cypher> CONFIRM=1
Then:  make centralidad && make healthcheck
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[0].parent))
from src.documents_loader import transcript_doc_ids  # noqa: E402
from src.neo4j_loader import get_driver  # noqa: E402

PATCHES = Path(__file__).resolve().parents[1] / "data" / "audit" / "patches"

Q = """
MATCH (a)-[r]->(b)
WHERE r.source_doc IN $docs
  AND a.entity_id IS NOT NULL AND b.entity_id IS NOT NULL
  AND NOT type(r) IN ['MENTIONED_IN','PART_OF']
RETURN a.entity_id AS src, b.entity_id AS tgt, type(r) AS type,
       r.source_chunk_id AS cid, r.source_doc AS doc, r.source_page AS page,
       r.source_quote AS quote, r.amount AS amount, r.currency AS currency,
       r.date AS date
ORDER BY doc, page, src, tgt, type
"""


def s(v) -> str:
    """Cypher single-quoted string literal (or null)."""
    if v is None:
        return "null"
    return "'" + str(v).replace("\\", "\\\\").replace("'", "\\'") + "'"


def n(v) -> str:
    return "null" if v is None else repr(v)


def main() -> None:
    stamp = sys.argv[1] if len(sys.argv) > 1 else "manual"
    docs = sorted(transcript_doc_ids())
    driver = get_driver()
    with driver.session() as sess:
        rows = sess.run(Q, docs=docs).data()
    driver.close()

    docs_lit = "[" + ",".join(s(d) for d in docs) + "]"
    mig = PATCHES / f"manual_fix_transcript_edges_{stamp}.cypher"
    rbk = PATCHES / f"manual_fix_transcript_edges_{stamp}.rollback.cypher"

    header = (
        "// GENERATED by gen_transcript_edge_cleanup.py — retira TODAS las aristas\n"
        "// entidad-entidad de los diarios de sesion (transcripcion_parlamentaria).\n"
        "// Option D (findings/aristas-transcripciones-parlamentarias, 2026-07-02):\n"
        f"// {len(rows)} aristas; ~65% boilerplate de encabezado, ~26% co-mencion,\n"
        "// ~24% a nodos no-actor + retorica/misatribucion; lo legitimo es redundante.\n"
        "// Document/Chunk/MENTIONED_IN INTACTOS: los docs siguen consultables.\n"
        "// REVISABLE Y REVERSIBLE (ver .rollback). Apply GATED: make qa-migrate FILE=... CONFIRM=1.\n"
        "// Tras aplicar: make centralidad && make healthcheck.\n\n"
    )
    mig.write_text(
        header
        + "MATCH (a)-[r]->(b)\n"
        f"WHERE r.source_doc IN {docs_lit}\n"
        "  AND a.entity_id IS NOT NULL AND b.entity_id IS NOT NULL\n"
        "  AND NOT type(r) IN ['MENTIONED_IN','PART_OF']\n"
        "DELETE r;\n"
    )

    lines = [
        "// ROLLBACK — recrea las aristas retiradas (misma clave source_chunk_id).\n"
        f"// {len(rows)} aristas. Apply GATED: make qa-migrate FILE=... CONFIRM=1.\n\n"
    ]
    for r in rows:
        lines.append(
            # apoc.create.relationship (not merge): tolerates null source_chunk_id
            # and null props (skipped); a rollback runs ONCE against a post-migration
            # store, so CREATE is exact and can't duplicate surviving edges.
            f"MATCH (a {{entity_id:{s(r['src'])}}}),(b {{entity_id:{s(r['tgt'])}}}) "
            f"CALL apoc.create.relationship(a,{s(r['type'])},"
            f"{{source_chunk_id:{s(r['cid'])},source_doc:{s(r['doc'])},"
            f"source_page:{n(r['page'])},source_quote:{s(r['quote'])},"
            f"amount:{n(r['amount'])},currency:{s(r['currency'])},date:{s(r['date'])}}},b) "
            "YIELD rel RETURN count(rel);\n"
        )
    rbk.write_text("".join(lines))
    print(f"docs: {docs}")
    print(f"edges: {len(rows)}")
    print(f"wrote {mig}")
    print(f"wrote {rbk}")


if __name__ == "__main__":
    main()
